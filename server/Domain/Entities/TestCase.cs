namespace SmartGrader.Domain.Entities
{
    public class TestCase
    {
        public string Input { get; set; }
        public string Expected { get; set; }

        /// <summary>
        /// מקרה "דוגמה" — היחיד שהתלמידה רואה. ברירת המחדל false היא הגנה מכוונת (fail closed):
        /// מקרי בדיקה קיימים ב-TestsJson נטענים בלי המאפיין הזה ולכן הופכים למוסתרים מאליהם,
        /// והמורה מסמנת דוגמאות מכאן והלאה. מוסתר = הקלט והפלט הצפוי לעולם לא נשלחים לתלמידה,
        /// גם לא אחרי הבדיקה. ר' TestVisibility.
        /// </summary>
        public bool IsSample { get; set; }

        /// <summary>
        /// מקרה "ליבה" — בודק את הדבר המרכזי שהתרגיל עוסק בו, להבדיל ממקרה קצה שבודק גבול
        /// או קלט חריג.
        /// <para>
        /// ⚠️ <b>היום אין לדגל הזה שום השפעה על הציון.</b> <c>AiWorker</c> מחשב
        /// <c>passed / total * 100</c> ותו לא. הדגל נשמר כדי שהסיווג שה-AI הציע והמורה אישרה
        /// לא יילך לאיבוד, וכדי שכשייכנס <c>ScoreCalculator</c> (plan-gradingRequirementsEngine)
        /// יהיה לו על מה לעבוד: שם מקרה ליבה שנכשל מאפס את נקודות הטסטים, בעוד מקרה קצה
        /// שנכשל עולה רק את חלקו היחסי.
        /// </para>
        /// <para>
        /// ברירת המחדל היא <c>true</c> — בניגוד ל-<see cref="IsSample"/>. הרוב המכריע של מקרי
        /// הבדיקה הם מקרי ליבה, והמורה מורידה את הסימון מהמיעוט. מקרים קיימים ב-TestsJson
        /// נטענים בלי המאפיין הזה, ו-System.Text.Json משאיר להם את ערך האתחול — כלומר הם
        /// הופכים למקרי ליבה, וזו ההתנהגות הרצויה (בלי אף מקרה ליבה אין שער ניקוד בכלל).
        /// </para>
        /// <para>הדגל אורתוגונלי ל-<see cref="IsSample"/>: זה קובע <i>מה התלמידה רואה</i>,
        /// וזה קובע <i>איך זה מנוקד</i>. מקרה ליבה יכול להיות גלוי או מוסתר.</para>
        /// </summary>
        public bool IsCore { get; set; } = true;
    }
}
